import { aiGeneratedByLabel, type AiGeneratedBy } from '@relay/shared';
import { cn } from '@/lib/utils';

/** The agent and model behind an AI answer, shown next to the answer. */
export function GeneratedBy({ by, className }: { by: AiGeneratedBy; className?: string }) {
  return (
    <p className={cn('text-2xs text-muted-foreground', className)}>
      Generated by {aiGeneratedByLabel(by)}
    </p>
  );
}
