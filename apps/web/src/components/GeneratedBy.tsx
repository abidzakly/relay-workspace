import { useEffect } from 'react';
import { agentModelLabel, aiGeneratedByLabel, type AiGeneratedBy } from '@relay/shared';
import { cn } from '@/lib/utils';
import { notifyGeneratedByFallback } from './ModelFallbackAlert';

/** The agent and model behind an AI answer, shown next to the answer. A refused model raises the fallback alert. */
export function GeneratedBy({ by, className }: { by: AiGeneratedBy; className?: string }) {
  useEffect(() => notifyGeneratedByFallback(by), [by]);
  return (
    <p className={cn('text-2xs text-muted-foreground', className)}>
      Generated by {aiGeneratedByLabel(by)}
      {by.fallbackFrom && (
        <span className="text-warning">
          {' '}
          · {agentModelLabel(by.fallbackFrom)} was not available
        </span>
      )}
    </p>
  );
}
