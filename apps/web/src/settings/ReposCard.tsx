import { useState } from 'react';
import { Pencil, Plus, Trash2, Zap } from 'lucide-react';
import type { GlobalConfigPublic, RepoConfigPublic } from '@relay/shared';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Label } from '@/components/ui/label';
import { Switch } from '@/components/ui/switch';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';
import { ConnectionChecklist } from '@/components/ConnectionChecklist';
import { describeError } from '@/lib/api';
import { useDeleteRepo, useRepos, useSetRepoEnabled, useTestRepo } from '@/lib/settingsApi';
import { cn } from '@/lib/utils';
import { RepoDialog } from './RepoDialog';
import { ErrorAlert, SectionCard } from './SectionCard';

function webhookUrl(settings: GlobalConfigPublic, id: string): string | null {
  const base = settings.publicBaseUrl?.replace(/\/+$/, '');
  return base ? `${base}/webhook/${id}` : null;
}

function RepoRow({
  repo,
  settings,
  onEdit,
  onDelete,
}: {
  repo: RepoConfigPublic;
  settings: GlobalConfigPublic;
  onEdit: () => void;
  onDelete: () => void;
}) {
  const test = useTestRepo();
  const toggle = useSetRepoEnabled();
  const hook = webhookUrl(settings, repo.id);
  const switchId = `repo-on-board-${repo.id}`;
  return (
    <li className="grid gap-3 rounded-lg border p-4">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div className={cn('min-w-0 transition-opacity', !repo.enabled && 'opacity-60')}>
          <div className="flex flex-wrap items-center gap-2">
            <span className="font-medium">{repo.name}</span>
            <code className="text-xs text-muted-foreground">{repo.id}</code>
            {!repo.enabled && <Badge variant="outline">off the board</Badge>}
          </div>
          <div className="mt-1.5 flex flex-wrap gap-1.5">
            <Badge variant="outline">project {repo.gitlab.projectId}</Badge>
            <Badge variant="outline">base {repo.baseBranch}</Badge>
            <Badge variant="outline">{repo.approvalMode}</Badge>
            <Badge variant={repo.gitlab.tokenSet ? 'success' : 'destructive'}>
              {repo.gitlab.tokenSet ? 'token saved' : 'no token'}
            </Badge>
            <Badge variant={repo.gitlab.webhookSecretSet ? 'success' : 'warning'}>
              {repo.gitlab.webhookSecretSet ? 'webhook secret set' : 'no webhook secret'}
            </Badge>
          </div>
          <p className="mt-2 text-sm text-muted-foreground">
            Reviewers: {repo.reviewers.join(', ')}
          </p>
          <p className="text-sm break-all text-muted-foreground">
            Webhook:{' '}
            {hook ? <code>{hook}</code> : <span>set the public base URL (above) to see it</span>}
          </p>
          <p className="text-xs text-muted-foreground">
            The webhook secret is generated by the dashboard and never shown. Use Register under
            Webhook health to create the hook in GitLab with it; a hook added by hand has no secret
            and its deliveries are rejected (HTTP 401).
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <div className="flex items-center gap-2 pr-2">
            <Switch
              id={switchId}
              checked={repo.enabled}
              disabled={toggle.isPending}
              onCheckedChange={(enabled) => toggle.mutate({ id: repo.id, enabled })}
            />
            <Label htmlFor={switchId}>On the board</Label>
          </div>
          <Button
            variant="outline"
            size="sm"
            disabled={test.isPending}
            onClick={() => test.mutate(repo.id)}
          >
            <Zap />
            {test.isPending ? 'Testing…' : 'Test connection'}
          </Button>
          <Button variant="outline" size="sm" onClick={onEdit}>
            <Pencil />
            Edit
          </Button>
          <Button variant="outline" size="sm" onClick={onDelete}>
            <Trash2 />
            Delete
          </Button>
        </div>
      </div>
      {toggle.error ? <ErrorAlert error={toggle.error} /> : null}
      {test.error ? <ErrorAlert error={test.error} /> : null}
      {test.data ? <ConnectionChecklist result={test.data} /> : null}
    </li>
  );
}

export function ReposCard({ settings }: { settings: GlobalConfigPublic }) {
  const repos = useRepos();
  const del = useDeleteRepo();
  const [dialog, setDialog] = useState<{ open: boolean; repo: RepoConfigPublic | undefined }>({
    open: false,
    repo: undefined,
  });
  const [toDelete, setToDelete] = useState<RepoConfigPublic | null>(null);

  return (
    <SectionCard
      id="repos"
      title="Repositories"
      description="One entry per GitLab project. Only repos switched “On the board” put their cards on the Board. “Test connection” checks GitLab, sends a real test delivery to the repo's webhook, and checks its Drive folder, using the saved config."
      action={
        <Button onClick={() => setDialog({ open: true, repo: undefined })}>
          <Plus />
          Add repository
        </Button>
      }
    >
      {repos.isPending ? <p className="text-sm text-muted-foreground">Loading…</p> : null}
      {repos.error ? <ErrorAlert error={repos.error} /> : null}
      {repos.data && repos.data.length === 0 ? (
        <p className="text-sm text-muted-foreground">No repositories yet. Add your first one.</p>
      ) : null}
      {repos.data && repos.data.length > 0 ? (
        <ul className="grid gap-3">
          {repos.data.map((r) => (
            <RepoRow
              key={r.id}
              repo={r}
              settings={settings}
              onEdit={() => setDialog({ open: true, repo: r })}
              onDelete={() => {
                del.reset();
                setToDelete(r);
              }}
            />
          ))}
        </ul>
      ) : null}

      <RepoDialog
        open={dialog.open}
        repo={dialog.repo}
        onOpenChange={(open) => setDialog((d) => ({ ...d, open }))}
      />

      <Dialog open={toDelete !== null} onOpenChange={(open) => !open && setToDelete(null)}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>Delete {toDelete?.name}?</DialogTitle>
            <DialogDescription>
              This removes the repository's configuration and its stored token and webhook secret
              from the dashboard. Nothing in GitLab, Notion or Drive is changed, and a webhook
              already registered in GitLab is not removed. The change is recorded in Audit.
            </DialogDescription>
          </DialogHeader>
          {del.error ? (
            <p role="alert" className="text-sm text-destructive">
              {describeError(del.error)}
            </p>
          ) : null}
          <DialogFooter>
            <Button variant="outline" onClick={() => setToDelete(null)}>
              Cancel
            </Button>
            <Button
              variant="destructive"
              disabled={del.isPending}
              onClick={() => {
                if (!toDelete) return;
                del.mutate(toDelete.id, { onSuccess: () => setToDelete(null) });
              }}
            >
              {del.isPending ? 'Deleting…' : 'Delete repository'}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </SectionCard>
  );
}
